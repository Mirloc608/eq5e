// EQ5e Tool — Auto‑Generated Header

// tools/generate-tool-docs.js
// Generates TOOLS.md documentation from the contents of the /tools directory.

export default async function generateToolDocs({ strict = false } = {}) {
  const fs = await import("node:fs");
  const path = await import("node:path");
  const url = await import("node:url");

  try {
    const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
    const root = path.resolve(__dirname, "..");
    const toolsDir = path.join(root, "tools");
    const outPath = path.join(root, "TOOLS.md");

    const files = fs
      .readdirSync(toolsDir)
      .filter(f => f.endsWith(".js"))
      .filter(f => f !== "cli.mjs" && f !== "dependency-graph.js");

    const docs = [];

    for (const file of files) {
      const full = path.join(toolsDir, file);
      const src = fs.readFileSync(full, "utf8");

      const lines = src.split("\n");

      // Extract header comment
      let header = "";
      for (const line of lines) {
        if (line.startsWith("// EQ5e Tool")) continue;
        if (line.startsWith("//")) {
          header += line.replace(/^\/\/\s?/, "") + "\n";
        } else {
          break;
        }
      }

      header = header.trim();

      // Extract exported function signature
      const fnMatch = src.match(/export\s+default\s+async\s+function\s+(\w+)\s*\((.*?)\)/);
      const fnName = fnMatch ? fnMatch[1] : "unknownTool";
      const fnArgs = fnMatch ? fnMatch[2] : "";

      docs.push({
        file,
        fnName,
        fnArgs,
        header
      });
    }

    // Build TOOLS.md
    let md = `# EQ5e Toolchain Documentation\n\n`;
    md += `This file is auto‑generated by \`generate-tool-docs.js\`.\n\n`;

    md += `## Table of Contents\n`;
    for (const d of docs) {
      md += `- [${d.fnName}](#${d.fnName.toLowerCase()})\n`;
    }
    md += `\n---\n\n`;

    for (const d of docs) {
      md += `## ${d.fnName}\n\n`;
      md += `**File:** \`${d.file}\`\n\n`;
      md += `**Signature:**\n\n`;
      md += `\`\`\`js\n${d.fnName}(${d.fnArgs})\n\`\`\`\n\n`;

      if (d.header) {
        md += `**Description:**\n\n`;
        md += `${d.header}\n\n`;
      }

      md += `---\n\n`;
    }

    fs.writeFileSync(outPath, md);
    console.log("✔ generate-tool-docs created TOOLS.md");
  } catch (err) {
    console.log("⚠ generate-tool-docs encountered an error");
    if (strict) throw err;
  }
}

